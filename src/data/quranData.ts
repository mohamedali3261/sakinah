// Helper function to fetch full Surah text and audio dynamically from the Quran API
export async function fetchFullSurah(surahNumber: number): Promise<QuranSurah> {
  // If we have inlined Surah, return it directly or fetch from API
  if (INLINE_SURAHS[surahNumber]) {
    return INLINE_SURAHS[surahNumber];
  }

  const meta = SURAHS_METADATA.find((s) => s.number === surahNumber);
  if (!meta) throw new Error('Surah not found');

  try {
    const res = await fetch(`https://api.alquran.cloud/v1/surah/${surahNumber}/editions/quran-uthmani,en.sahih`);
    if (!res.ok) throw new Error('Failed to fetch from Quran API');
    const data = await res.json();
    const arData = data.data[0];
    const enData = data.data[1];

    const verses = arData.ayahs.map((ayah: any, index: number) => {
      let text = ayah.text;
      // If surah is not Al-Fatiha and verse 1, strip bismillah prefix if present
      if (surahNumber !== 1 && ayah.numberInSurah === 1 && text.startsWith('بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ')) {
        text = text.replace('بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ', '').trim();
      }
      return {
        id: ayah.number,
        verseNumber: ayah.numberInSurah,
        textAr: text || ayah.text,
        textEn: enData.ayahs[index]?.text || '',
        juz: ayah.juz,
        page: ayah.page
      };
    });

    return {
      number: meta.number,
      nameAr: meta.nameAr,
      nameEn: meta.nameEn,
      englishMeaning: meta.englishMeaning,
      versesCount: meta.versesCount,
      revelationType: meta.revelationType,
      revelationOrder: meta.revelationOrder,
      juzStart: meta.juzStart,
      bismillahPre: meta.number !== 9 && meta.number !== 1,
      verses
    };
  } catch (err) {
    // Fallback if offline or API blocked
    return {
      number: meta.number,
      nameAr: meta.nameAr,
      nameEn: meta.nameEn,
      englishMeaning: meta.englishMeaning,
      versesCount: meta.versesCount,
      revelationType: meta.revelationType,
      revelationOrder: meta.revelationOrder,
      juzStart: meta.juzStart,
      bismillahPre: meta.number !== 9,
      verses: [
        {
          id: 1,
          verseNumber: 1,
          textAr: `سُورَةُ ${meta.nameAr} - ${meta.revelationType === 'Meccan' ? 'مكية' : 'مدنية'} وعدد آياتها ${meta.versesCount} آية.`,
          textEn: `Surah ${meta.nameEn} (${meta.englishMeaning}) - ${meta.versesCount} Verses.`,
          juz: meta.juzStart,
          page: 1
        }
      ]
    };
  }
}
