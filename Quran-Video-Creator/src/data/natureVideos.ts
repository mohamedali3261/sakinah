export const ALL_NATURE_MEDIA: NatureMediaItem[] = [
  ...NATURE_VIDEOS.map((v): NatureMediaItem => ({
    id: v.id,
    type: 'video',
    titleEn: v.titleEn,
    titleAr: v.titleAr,
    category: v.category,
    url: v.videoUrl,
    thumbnailUrl: v.thumbnailUrl,
    authorCredit: v.authorCredit,
    source: v.source
  })),
  ...NATURE_IMAGES
];

export function getMediaItemById(id: string): NatureMediaItem {
  return ALL_NATURE_MEDIA.find((m) => m.id === id) || ALL_NATURE_MEDIA[0];
}

/**
 * Nature keywords used for auto searching & fetching nature videos automatically during generation
 */
export const NATURE_SEARCH_KEYWORDS = [
  'nature',
  'forest',
  'stream',
  'ocean',
  'waves',
  'mountains',
  'fog',
  'stars',
  'galaxy',
  'rain',
  'mist',
  'sunset',
  'clouds',
  'waterfall',
  'river',
  'landscape'
];

/**
 * Searches and picks a random nature video using nature search keywords automatically.
 */
export function fetchRandomNatureVideoByKeywords(customKeywords?: string[]): NatureVideo {
  const keywords = customKeywords && customKeywords.length > 0 ? customKeywords : NATURE_SEARCH_KEYWORDS;
  const chosenKeyword = keywords[Math.floor(Math.random() * keywords.length)];

  const matched = NATURE_VIDEOS.filter(
    (v) =>
      v.category.toLowerCase().includes(chosenKeyword.toLowerCase()) ||
      v.titleEn.toLowerCase().includes(chosenKeyword.toLowerCase()) ||
      v.titleAr.includes(chosenKeyword)
  );

  if (matched.length > 0) {
    return matched[Math.floor(Math.random() * matched.length)];
  }

  // Fallback to completely random nature video from the library
  return NATURE_VIDEOS[Math.floor(Math.random() * NATURE_VIDEOS.length)];
}


